def flow_document(
    uuid: str,
    name: str,
    unit: str,
    flow_property_uuid: str,
    *,
    elementary: bool,
    categories: Sequence[str] = (),
) -> dict[str, Any]:
    classification = (
        {
            "common:elementaryFlowCategorization": {
                "common:category": _elementary_classes(categories)
            }
        }
        if elementary
        else {
            "common:classification": [
                {
                    "@name": "tidas-bw generated classification",
                    "common:class": [
                        {
                            "@level": "0",
                            "@classId": "unclassified",
                            "#text": "Unclassified product flow generated from Brightway",
                        },
                    ],
                }
            ]
        }
    )
    return {
        "flowDataSet": {
            "@xmlns": "http://lca.jrc.it/ILCD/Flow",
            "@xmlns:common": "http://lca.jrc.it/ILCD/Common",
            "@xmlns:ecn": "http://eplca.jrc.ec.europa.eu/ILCD/Extensions/2018/ECNumber",
            "@xmlns:xsi": "http://www.w3.org/2001/XMLSchema-instance",
            "@version": "1.1",
            "@locations": "../ILCDLocations.xml",
            "@xsi:schemaLocation": "http://lca.jrc.it/ILCD/Flow ../../schemas/ILCD_FlowDataSet.xsd",
            "flowInformation": {
                "dataSetInformation": {
                    "common:UUID": uuid,
                    "name": {
                        "baseName": multilingual(name),
                        "treatmentStandardsRoutes": multilingual("unspecified"),
                        "mixAndLocationTypes": multilingual("generated migration flow"),
                    },
                    "classificationInformation": classification,
                    "common:generalComment": multilingual(
                        "Original Brightway categories: "
                        + (" / ".join(str(item) for item in categories) or "not provided")
                        if elementary
                        else "No authoritative product classification was available in Brightway; this flow remains explicitly unclassified."
                    ),
                },
                "quantitativeReference": {"referenceToReferenceFlowProperty": "0"},
            },
            "modellingAndValidation": {
                "LCIMethod": {"typeOfDataSet": "Elementary flow" if elementary else "Product flow"},
                "complianceDeclarations": {"compliance": small_compliance()},
            },
            "administrativeInformation": {
                "dataEntryBy": {
                    "common:timeStamp": TIMESTAMP,
                    "common:referenceToDataSetFormat": format_reference(),
                },
                "publicationAndOwnership": publication(uuid),
            },
            "flowProperties": {
                "flowProperty": {
                    "@dataSetInternalID": "0",
                    "referenceToFlowPropertyDataSet": global_reference(
                        "flowproperties", flow_property_uuid, f"Quantity in {unit}"
                    ),
                    "meanValue": "1",
                }
            },
        }
    }


