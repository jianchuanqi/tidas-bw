def process_instance(
    internal_id: int,
    process_uuid: str,
    process_name: str,
    *,
    connections: Sequence[Mapping[str, Any]] = (),
) -> dict[str, Any]:
    result: dict[str, Any] = {
        "@dataSetInternalID": str(internal_id),
        "@multiplicationFactor": "1",
        "referenceToProcess": global_reference("processes", process_uuid, process_name),
    }
    if connections:
        result["connections"] = {"outputExchange": list(connections)}
    return result


def model_connection(
    flow_uuid: str,
    downstream_ids: Sequence[int],
) -> dict[str, Any]:
    downstream = [
        {
            "@id": str(identifier),
            "@flowUUID": flow_uuid,
            "@version": VERSION,
        }
        for identifier in downstream_ids
    ]
    return {
        "@flowUUID": flow_uuid,
        "@version": VERSION,
        "downstreamProcess": downstream[0] if len(downstream) == 1 else downstream,
    }


def _elementary_classes(categories: Sequence[str]) -> list[dict[str, str]]:
    text = " / ".join(str(item).lower() for item in categories)
    if "resource" in text or "natural" in text:
        if "water" in text:
            values = (
                ("0", "2", "Resources"),
                ("1", "2.2", "Resources from water"),
            )
        elif "air" in text:
            values = (
                ("0", "2", "Resources"),
                ("1", "2.3", "Resources from air"),
            )
        elif "biosphere" in text or "biotic" in text:
            values = (
                ("0", "2", "Resources"),
                ("1", "2.4", "Resources from biosphere"),
            )
        elif "ground" in text or "soil" in text:
            values = (
                ("0", "2", "Resources"),
                ("1", "2.1", "Resources from ground"),
            )
        else:
            values = (("0", "2", "Resources"),)
    elif "water" in text:
        values = (
            ("0", "1", "Emissions"),
            ("1", "1.1", "Emissions to water"),
            ("2", "1.1.3", "Emissions to water, unspecified"),
        )
    elif "soil" in text:
        values = (
            ("0", "1", "Emissions"),
            ("1", "1.2", "Emissions to soil"),
            ("2", "1.2.3", "Emissions to soil, unspecified"),
        )
    elif "air" in text:
        values = (
            ("0", "1", "Emissions"),
            ("1", "1.3", "Emissions to air"),
            ("2", "1.3.4", "Emissions to air, unspecified"),
        )
    else:
        values = (("0", "4", "Other elementary flows"),)
    return [
        {"@level": level, "@catId": identifier, "#text": label}
        for level, identifier, label in values
    ]
