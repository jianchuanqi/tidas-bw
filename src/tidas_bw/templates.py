from .utils import multilingual, number_string

VERSION = "01.00.000"
TIMESTAMP = "2000-01-01T00:00:00Z"
NAMESPACE = UUID("2197f8e8-a5e7-4a3d-95e0-5560c46a0aa6")
OWNER_UUID = str(uuid5(NAMESPACE, "tidas-bw:owner"))
FORMAT_SOURCE_UUID = str(uuid5(NAMESPACE, "tidas-bw:format-source"))


def stable_uuid(value: str) -> str:
    return str(uuid5(NAMESPACE, value))


def global_reference(
    category: str,
    uuid: str,
    description: str,
    *,
    version: str = VERSION,
) -> dict[str, Any]:
    type_name = {
        "contacts": "contact data set",
        "sources": "source data set",
        "unitgroups": "unit group data set",
        "flowproperties": "flow property data set",
        "flows": "flow data set",
        "processes": "process data set",
        "lifecyclemodels": "life cycle model data set",
        "lciamethods": "LCIA method data set",
    }[category]
    return {
        "@type": type_name,
        "@refObjectId": uuid,
        "@version": version,
        "@uri": f"../{category}/{uuid}_{version}.json",
        "common:shortDescription": multilingual(description),
    }


def owner_reference() -> dict[str, Any]:
    return global_reference("contacts", OWNER_UUID, "tidas-bw generated data owner")


def format_reference() -> dict[str, Any]:
    return global_reference("sources", FORMAT_SOURCE_UUID, "TIDAS JSON generated by tidas-bw")


def small_compliance() -> dict[str, Any]:
    return {
        "common:referenceToComplianceSystem": format_reference(),
        "common:approvalOfOverallCompliance": "Not defined",
    }


def full_compliance() -> dict[str, Any]:
    return {
        **small_compliance(),
        "common:nomenclatureCompliance": "Not defined",
        "common:methodologicalCompliance": "Not defined",
        "common:reviewCompliance": "Not defined",
        "common:documentationCompliance": "Not defined",
        "common:qualityCompliance": "Not defined",
    }


def publication(uuid: str) -> dict[str, Any]:
    return {
        "common:dataSetVersion": VERSION,
        "common:permanentDataSetURI": f"urn:uuid:{uuid}",
        "common:referenceToOwnershipOfDataSet": owner_reference(),
        "common:copyright": "false",
        "common:licenseType": "Free of charge for all users and uses",
    }


